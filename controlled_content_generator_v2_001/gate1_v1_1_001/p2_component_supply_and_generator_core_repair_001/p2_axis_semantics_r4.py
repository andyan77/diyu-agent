def _beat_groups(sequence: list[str], lane_id: str) -> list[list[str]]:
    if len(sequence) == 5:
        widths = [2, 2, 1] if lane_id == "A" else [1, 2, 2]
    elif len(sequence) == 4:
        widths = [2, 1, 1] if lane_id == "A" else [1, 1, 2]
    else:
        widths = [1] * len(sequence)
    groups: list[list[str]] = []
    cursor = 0
    for width in widths:
        groups.append(sequence[cursor : cursor + width])
        cursor += width
    return groups


def reviewed_value_programs() -> dict[str, dict[str, dict[str, dict[str, Any]]]]:
    programs: dict[str, dict[str, dict[str, dict[str, Any]]]] = {
        axis: {} for axis in AXIS_NAMES
    }
    for cp_id, design in CP_PATH_DESIGNS.items():
        for axis in AXIS_NAMES:
            programs[axis][cp_id] = {}
        for lane_id, design_key in (("A", "a"), ("B", "b")):
            plan = SEMANTIC_LANE_PLANS[cp_id][lane_id]
            axis_values = dict(zip(AXIS_NAMES, design[design_key], strict=True))
            for axis, value in axis_values.items():
                common = {
                    "axis": axis,
                    "reviewed_parameter_value": value,
                    "applicable_profile_id": cp_id,
                    "lane_designation": lane_id,
                    "unknown_or_other_profile_behavior": "REJECT",
                    "may_add_or_change_fact": False,
                    "may_add_or_change_authorization": False,
                }
                if axis == "narrative_mechanism":
                    body = {
                        "semantic_action": plan["relation"],
                        "ordered_fact_slots": plan["sequence"],
                        "relation_mode": plan["relation"],
                        "stop_boundary_slots": plan["ending_slots"],
                    }
                elif axis == "information_order":
                    body = {
                        "semantic_action": "APPLY_EXPLICIT_INFORMATION_SEQUENCE",
                        "ordered_fact_slots": plan["sequence"],
                        "ordering_is_authoritative": True,
                    }
                elif axis == "visual_subject":
                    body = {
                        "semantic_action": plan["visual_mode"],
                        "lead_fact_slot": plan["visual_lead"],
                        "supporting_fact_slots": plan["visual_support"],
                        "focus_mode": plan["visual_mode"],
                    }
                elif axis == "sound_subject":
                    body = {
                        "semantic_action": plan["sound_mode"],
                        "cue_fact_slots": plan["sound_slots"],
                        "cue_source_class": plan["sound_mode"],
                        "missing_source_behavior": "USE_SILENCE_NOT_INVENTED_SOUND",
                    }
                elif axis == "rhythm":
                    body = {
                        "semantic_action": plan["cadence"],
                        "beat_fact_slot_groups": _beat_groups(plan["sequence"], lane_id),
                        "cadence_mode": plan["cadence"],
                        "chronology_policy": "PRESERVE_LANE_INFORMATION_ORDER",
                    }
                else:
                    body = {
                        "semantic_action": plan["closure_mode"],
                        "boundary_fact_slots": plan["ending_slots"],
                        "closure_mode": plan["closure_mode"],
                        "next_step_policy": plan["next_step_policy"],
                        "claims_resolved": False,
                        "may_add_commitment": False,
                    }
                programs[axis][cp_id][value] = {**common, **body}
    return programs


REVIEWED_VALUE_PROGRAMS = reviewed_value_programs()
